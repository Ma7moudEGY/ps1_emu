use super::instruction::Instruction;
use super::ops::*;

pub(super) fn decode(mut instruction: Instruction) -> Instruction {
    instruction.execute = match instruction.function() {
            0b000000    =>  {
                let sub_funct = instruction.sub_function();
                match sub_funct {
                    0x00    => op_sll,
                    0x02    => op_srl,
                    0x03    => op_sra,
                    0x04    => op_sllv,
                    0x06    => op_srlv,
                    0x07    => op_srav,
                    0x08    => op_jr,
                    0x09    => op_jalr,
                    0x0c    => op_syscall,
                    0x0d    => op_break,
                    0x10    => op_mfhi,
                    0x11    => op_mthi,
                    0x12    => op_mflo,
                    0x13    => op_mtlo,
                    0x18    => op_mult,
                    0x19    => op_multu,
                    0x1a    => op_div,
                    0x1b    => op_divu,
                    0x20    => op_add,
                    0x21    => op_addu,
                    0x22    => op_sub,
                    0x23    => op_subu,
                    0x24    => op_and,
                    0x25    => op_or,
                    0x26    => op_xor,
                    0x27    => op_nor,
                    0x2a    => op_slt,
                    0x2b    => op_sltu,
                    _       => op_illegal,
                }
            },
            0b000001    => op_bxx,
            0b000010    => op_j,
            0b000011    => op_jal,
            0b000100    => op_beq,
            0b000101    => op_bne,
            0b000110    => op_blez,
            0b000111    => op_bgtz,
            0b001000    => op_addi,
            0b001001    => op_addiu,
            0b001010    => op_slti,
            0b001011    => op_sltiu,
            0b001110    => op_xori,
            0b001111    => op_lui,
            0b001100    => op_andi,
            0b001101    => op_ori,
            0b010000    => op_cop0,
            0b010001    => op_cop1,
            0b010010    => op_cop2,
            0b010011    => op_cop3,
            0b100000    => op_lb,
            0b100001    => op_lh,
            0b100010    => op_lwl,
            0b100011    => op_lw,
            0b100100    => op_lbu,
            0b100101    => op_lhu,
            0b100110    => op_lwr,
            0b101000    => op_sb,
            0b101001    => op_sh,
            0b101010    => op_swl,
            0b101011    => op_sw,
            0b101110    => op_swr,
            0b110000    => op_lwc0,
            0b110001    => op_lwc1,
            0b110010    => op_lwc2,
            0b110011    => op_lwc3,
            0b111000    => op_swc0,
            0b111001    => op_swc1,
            0b111010    => op_swc2,
            0b111011    => op_swc3,
            _           => op_illegal,
        };

        instruction
}